def _build_adjacent() -> dict[str, set[str]]:
    adjacent: dict[str, set[str]] = {}
    for a, b in _BORDERS:
        adjacent.setdefault(a, set()).add(b)
        adjacent.setdefault(b, set()).add(a)
    return adjacent


ADJACENT_PROVINCES: dict[str, set[str]] = _build_adjacent()


def zone_tier(origin_province: str, destination_province: str) -> str:
    """Return "same", "adjacent", or "far" for two Iranian provinces."""
    origin = (origin_province or "").strip()
    dest = (destination_province or "").strip()
    if origin and dest and origin == dest:
        return "same"
    if origin and dest and dest in ADJACENT_PROVINCES.get(origin, set()):
        return "adjacent"
    return "far"
